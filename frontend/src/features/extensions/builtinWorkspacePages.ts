function lazyPage<TModule extends Record<string, unknown>>(
  loader: () => Promise<TModule>,
  exportName: keyof TModule,
): ExtensionPageComponent {
  return lazy(() =>
    loader().then((mod) => ({
      default: mod[exportName] as ComponentType<ExtensionPageComponentProps>,
    })),
  )
}

