func TestLoadUsesProductionEnvelopeAndEnvironmentOverrides(t *testing.T) {
	dir := t.TempDir()
	path := filepath.Join(dir, "production.json")
	body := `{
		"environment": {
			"ASTRORDER_HOST": "0.0.0.0",
			"ASTRORDER_PORT": 30001,
			"ASTRORDER_STATIC_DIR": "from-file",
			"ASTRORDER_ALLOWED_ORIGINS": "http://127.0.0.1:30001, https://astrorder.example",
			"ASTRORDER_UNUSED_LARGE_NUMBER": 9007199254740993
		},
		"user_metadata": {"preserved_by_provision": true}
	}`
	if err := os.WriteFile(path, []byte(body), 0o600); err != nil {
		t.Fatal(err)
	}
	t.Setenv("ASTRORDER_PORT", "31001")
	t.Setenv("ASTRORDER_BROWSER_SECRET", "env-browser")
	t.Setenv("ASTRORDER_CONNECTOR_SECRET", "env-connector")

	cfg, err := Load(path)
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Listen != "0.0.0.0:31001" {
		t.Fatalf("Listen = %q", cfg.Listen)
	}
	if cfg.StaticDir != "from-file" || cfg.BrowserSecret != "env-browser" || cfg.ConnectorSecret != "env-connector" {
		t.Fatalf("unexpected config: %#v", cfg)
	}
	if len(cfg.AllowedOrigins) != 2 || cfg.AllowedOrigins[1] != "https://astrorder.example" {
		t.Fatalf("AllowedOrigins = %#v", cfg.AllowedOrigins)
	}
}

func TestEnvironmentStringPreservesJSONNumberLexeme(t *testing.T) {
	for input, want := range map[string]string{
		"9007199254740993": "9007199254740993",
		"1.2300e+40":       "1.2300e+40",
	} {
		got, err := environmentString(json.Number(input))
		if err != nil || got != want {
			t.Fatalf("environmentString(%q) = %q, %v; want %q", input, got, err, want)
		}
	}
}

func TestLoadDoesNotInventCredentials(t *testing.T) {
	cfg, err := Load("")
	if err != nil {
		t.Fatal(err)
	}
	if cfg.BrowserSecret != "" || cfg.ConnectorSecret != "" {
		t.Fatal("credentials must not be generated by config loading")
	}
}

func TestLoadExplicitMigrationOwnership(t *testing.T) {
	t.Setenv("ASTRORDER_MIGRATION_UPSTREAM", "http://127.0.0.1:39001")
	t.Setenv("ASTRORDER_MIGRATION_BROWSER_SECRET", "upstream-browser")
	t.Setenv("ASTRORDER_MIGRATION_CONNECTOR_SECRET", "upstream-connector")
	t.Setenv("ASTRORDER_MIGRATION_ROUTES", `[
		{"method":"GET","path":"/api/v1/sessions/{session_id}","audience":"browser"},
		{"method":"GET","path":"/ws/v1/events","websocket":true,"audience":"browser"}
	]`)

	cfg, err := Load("")
	if err != nil {
		t.Fatal(err)
	}
	if cfg.Migration.Upstream != "http://127.0.0.1:39001" || len(cfg.Migration.Routes) != 2 {
		t.Fatalf("Migration = %#v", cfg.Migration)
	}
	if !cfg.Migration.Routes[1].WebSocket {
		t.Fatal("websocket ownership was lost")
	}
}

func TestLoadRejectsUnsafeOrInvalidValues(t *testing.T) {
	t.Run("plaintext secret in config", func(t *testing.T) {
		path := filepath.Join(t.TempDir(), "production.json")
		if err := os.WriteFile(path, []byte(`{"environment":{"ASTRORDER_BROWSER_SECRET":"plaintext"}}`), 0o600); err != nil {
			t.Fatal(err)
		}
		if _, err := Load(path); err == nil {
			t.Fatal("expected plaintext secret error")
		}
	})
	t.Run("wildcard origin", func(t *testing.T) {
		t.Setenv("ASTRORDER_ALLOWED_ORIGINS", "*")
		if _, err := Load(""); err == nil {
			t.Fatal("expected wildcard origin error")
		}
	})
	t.Run("port", func(t *testing.T) {
		t.Setenv("ASTRORDER_PORT", "70000")
		if _, err := Load(""); err == nil {
			t.Fatal("expected port error")
		}
	})
	t.Run("route JSON", func(t *testing.T) {
		t.Setenv("ASTRORDER_MIGRATION_ROUTES", "not-json")
		if _, err := Load(""); err == nil {
			t.Fatal("expected route JSON error")
		}
	})
}
